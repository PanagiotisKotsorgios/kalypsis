using Kalypsis.Domain.Entities;
using Microsoft.EntityFrameworkCore;

namespace Kalypsis.Infrastructure.Persistence.Seeders;

/// <summary>
/// Additive seeder for the public «Οδηγίες Χρήσης» documentation tree.
/// Runs on every boot. Inserts only the slugs that don't already exist —
/// PlatformAdmin edits to existing rows are never overwritten, and new
/// entries added to this file get picked up on the next deploy without
/// manual intervention.
/// </summary>
public static class DocumentationSeeder
{
    public static async Task SeedIfEmptyAsync(AppDbContext db, CancellationToken ct = default)
    {
        var existing = await db.DocumentationSections.IgnoreQueryFilters()
            .Select(s => s.Slug).ToListAsync(ct);
        var existingSet = new HashSet<string>(existing, StringComparer.Ordinal);
        var now = DateTime.UtcNow;

        // Sibling counters so newly-added sections land in the right order
        // regardless of what's already in the DB — top-level rank is derived
        // from the order this method calls Add() for them.
        var topRank = new Dictionary<string, int>();
        int topOrder = 0;
        int childOrder = 0;
        string? lastParent = null;

        void Add(string slug, string? parent, string title, string bodyHtml, string keywords)
        {
            // Recompute the sibling counter when the parent changes so we
            // never emit two rows with the same DisplayOrder within a group.
            if (parent != lastParent) { childOrder = 0; lastParent = parent; }
            var order = parent is null ? topOrder++ : childOrder++;
            topRank[slug] = order;

            if (existingSet.Contains(slug)) return;
            db.DocumentationSections.Add(new DocumentationSection
            {
                Id = Guid.NewGuid(),
                Slug = slug,
                ParentSlug = parent,
                Title = title,
                BodyHtml = bodyHtml,
                Keywords = keywords,
                DisplayOrder = order,
                IsPublished = true,
                CreatedAt = now,
            });
        }

