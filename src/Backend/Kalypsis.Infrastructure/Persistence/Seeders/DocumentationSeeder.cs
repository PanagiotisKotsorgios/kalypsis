using Kalypsis.Domain.Entities;
using Microsoft.EntityFrameworkCore;

namespace Kalypsis.Infrastructure.Persistence.Seeders;

/// <summary>
/// One-shot seeder for the public «Οδηγίες Χρήσης» documentation tree.
/// Populates documentation_sections with the Greek content that used to
/// live as a hardcoded array in DocumentationPage.tsx. Runs only when the
/// table is empty — subsequent runs are no-ops so PlatformAdmin edits
/// from /app/platform/documentation never get overwritten.
/// </summary>
public static class DocumentationSeeder
{
    public static async Task SeedIfEmptyAsync(AppDbContext db, CancellationToken ct = default)
    {
        if (await db.DocumentationSections.IgnoreQueryFilters().AnyAsync(ct))
            return;

