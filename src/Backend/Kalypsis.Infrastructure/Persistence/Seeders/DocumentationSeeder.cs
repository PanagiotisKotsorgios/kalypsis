                Id = Guid.NewGuid(),
                Slug = slug,
                ParentSlug = parent,
                Title = title,
                BodyHtml = bodyHtml,
                Keywords = keywords,
                DisplayOrder = parent is null ? order++ : childOrder++,
                IsPublished = true,
                CreatedAt = now,
